"""Exporting one approved report into the vault — deterministically, on request.

**Only ``immutable`` reports export** (section 2.8, rule 1): a draft was never agreed to
and a rejected run was declined, so neither may leave a trace in the vault. Nothing
exports automatically; the report page and the CLI both call this, and both only when a
person asked.

**A second export is the first export.** Every note is a function of the database state
and the reports' own approval dates — no wall clock reaches a byte — so re-exporting an
unchanged report rewrites identical files. What changes between exports is only the
``obsidian_exports`` row recording the act.

**Every link the export writes resolves.** The export covers the connected component of
the competitor *and theme* relations around the subject (see :mod:`aer.obsidian.graph`):
run and source notes for every approved run of every company in it, a company note for
each — a stub, honestly labelled, where a company was named as a comparable but never
researched — plus the catalyst, industry and theme notes those runs' notes point at.
Closure is what makes the vault a journal rather than a folder of exports.
"""

