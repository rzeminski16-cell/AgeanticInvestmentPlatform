async def _sources_for(session: AsyncSession, *, job_id: uuid.UUID) -> list[SourceDocument]:
    rows = await session.scalars(
        select(SourceDocument)
        .where(SourceDocument.job_id == job_id, SourceDocument.quarantined.is_(False))
        .options(selectinload(SourceDocument.artefact))
        .order_by(SourceDocument.url)
    )
    return list(rows)


async def _supported_claims(
    session: AsyncSession, *, job_id: uuid.UUID
) -> list[tuple[Claim, SourceDocument]]:
    """Numeric and factual claims with a verified citation, each with one source to link.

    The first verified citation's source, by claim order: the note links a reader to
    evidence, and the claim page in the app remains the place to see all of it.
    """
    rows = list(
        await session.scalars(
            select(Claim)
            .join(ReportSection, ReportSection.id == Claim.report_section_id)
            .where(
                ReportSection.job_id == job_id,
                Claim.kind.in_((ClaimKind.NUMERIC, ClaimKind.FACTUAL)),
            )
            .options(selectinload(Claim.citations))
            .order_by(Claim.created_at, Claim.id)
        )
    )
    found: list[tuple[Claim, SourceDocument]] = []
    for claim in rows:
        verified = [citation for citation in claim.citations if citation.excerpt_verified]
        if not verified:
            continue
        source = await session.get(SourceDocument, verified[0].source_document_id)
        if source is not None:
            found.append((claim, source))
    return found


async def _custom_sections(session: AsyncSession, *, job_id: uuid.UUID) -> list[dict[str, Any]]:
    rows = await session.execute(
        select(ReportSection.section_key, SectionDefinition)
        .join(SectionDefinition, SectionDefinition.id == ReportSection.section_definition_id)
        .where(ReportSection.job_id == job_id, SectionDefinition.origin == "skill")
        .order_by(ReportSection.position)
    )
    return [
        {
            "key": key,
            "skill": f"{key}@{definition.version}",
            "title": definition.title,
            "tags": ["aer/custom-section"],
        }
        for key, definition in rows.tuples()
    ]


# -- Names -------------------------------------------------------------------------------------


def _safe(text: str) -> str:
    return _UNSAFE.sub("-", text).strip()


def _run_note_title(request: ResearchRequest) -> str:
    return f"{request.work_order.as_of_date.isoformat()} {_safe(request.ticker)}"


def _company_note_title(request: ResearchRequest, company_name: str) -> str:
    return f"{_safe(request.ticker)} - {_safe(company_name)}"


def _company_title(company: Company) -> str:
    return f"{_safe(company.ticker)} - {_safe(company.name)}"


def _industry_note_title(profile: SectorProfile) -> str:
    return _safe(profile.label)


def _catalyst_note_title(company: Company, label: str) -> str:
    return f"{_safe(company.ticker)} {_safe(label)[:60].strip()}"


def _source_note_title(source: SourceDocument) -> str:
    digest = source.artefact.sha256[:6] if source.artefact else str(source.id)[:6]
    label = _safe(source.title or source.url)[:60].strip()
    return f"src-{digest} - {label}"


def _source_relative(source: SourceDocument) -> str:
    return f"90-Sources/{_source_note_title(source)}.md"


def _valuation_dict(report: Report) -> dict[str, Any] | None:
    if report.valuation_low is None or report.valuation_high is None:
        return None
    valuation: dict[str, Any] = {
        "low": str(report.valuation_low),
        "high": str(report.valuation_high),
        "currency": report.valuation_currency,
        "per": "share",
    }
    if report.valuation_base is not None:
        valuation["base"] = str(report.valuation_base)
    return valuation
